function fields = get_plot2_signal_panel_fields(signalFigure, signalAxes)
%GET_PLOT2_SIGNAL_PANEL_FIELDS Return per-panel UserData field names.

suffix = '';
if isgraphics(signalFigure) && isstruct(signalFigure.UserData) && ...
        ~isempty(signalAxes) && isgraphics(signalAxes) && ...
        isfield(signalFigure.UserData, 'plot2ComparisonAxes') && ...
        isequal(signalFigure.UserData.plot2ComparisonAxes, signalAxes)
    suffix = 'Comparison';
end

prefix = ['plot2' suffix 'Profile'];
fields = struct( ...
    'name', [prefix 'Name'], ...
    'signals', [prefix 'Signals'], ...
    'lines', [prefix 'Lines'], ...
    'legend', ['plot2' suffix 'Legend'], ...
    'unavailable', ['plot2' suffix 'UnavailableSignals']);
end
