classdef TestPlot2ComparisonFigure < matlab.unittest.TestCase
    methods (Test)
        function linksTimeRangeAndCursorAcrossSubplots(testCase)
            previousVisibility = get(0, 'DefaultFigureVisible');
            set(0, 'DefaultFigureVisible', 'off');
            testCase.addTeardown(@set, 0, 'DefaultFigureVisible', previousVisibility);

            signalFigure = figure;
            testCase.addTeardown(@delete_figure_if_valid, signalFigure);
            mainAxes = axes('Parent', signalFigure);
            mainLine = plot(mainAxes, [0 5 10], [0 1 0], ...
                'DisplayName', 'Main signal');
            mainLegend = legend(mainAxes, mainLine);
            mainLegend.UserData = struct( ...
                'Lines', mainLine, ...
                'BaseNames', {{'Main signal'}}, ...
                'DisplayNames', {{'Main signal'}}, ...
                'Highlighted', gobjects(0), ...
                'FixedAxesPosition', mainAxes.Position, ...
                'FixedPosition', mainLegend.Position);
            mainToggle = uicontrol(signalFigure, ...
                'Style', 'togglebutton', 'String', 'Cursor: OFF');
            signalFigure.UserData = struct( ...
                'cursorTool', struct( ...
                    'axes', mainAxes, ...
                    'legend', mainLegend, ...
                    'cursorLine', gobjects(0), ...
                    'currentTime', NaN, ...
                    'enabled', false, ...
                    'dragging', false, ...
                    'lastLegendUpdate', -Inf), ...
                'cursorToggle', mainToggle, ...
                'plot2ProfileName', 'Main', ...
                'plot2ProfileSignals', {{'MSG.B'}}, ...
                'plot2ProfileLines', mainLine, ...
                'plot2Legend', mainLegend);

            logData = struct('fileName', 'fixture', ...
                'MSG', struct('TimeS', [0; 1], 'A', [2; 4]));
            catalog = build_plot2_signal_catalog(logData, []);
            comparisonAxes = open_plot2_comparison_figure( ...
                signalFigure, logData, catalog, 0, []);

            testCase.verifyEqual(ancestor(comparisonAxes, 'figure'), signalFigure);
            testCase.verifyEqual(mainAxes.Position(3), 0.65, 'AbsTol', 1e-12);
            testCase.verifyEqual(comparisonAxes.Position(3), 0.65, 'AbsTol', 1e-12);
            testCase.verifyEqual(signalFigure.UserData.plot2ProfileLines, mainLine);
            testCase.verifyLessThan( ...
                signalFigure.UserData.plot2Legend.Position(4), 0.34);
            [comparisonLines, unavailableIds, comparisonLegend] = ...
                apply_plot2_signal_profile(signalFigure, comparisonAxes, ...
                    signalFigure.UserData.plot2ComparisonLegend, logData, catalog, ...
                    {'MSG.A'}, 0, []);
            testCase.verifyEmpty(unavailableIds);
            testCase.verifyEqual(comparisonLines.UserData.SignalId, 'MSG.A');
            testCase.verifyLessThan(comparisonLegend.Position(4), 0.34);
            signalFigure.UserData.plot2ComparisonProfileSignals = {'MSG.A'};
            signalFigure.UserData.plot2ComparisonLegend = comparisonLegend;
            testCase.verifyEqual( ...
                signalFigure.UserData.plot2ComparisonProfileSignals, {'MSG.A'});
            comparisonState = save_plot2_signal_profile_state( ...
                signalFigure, false, comparisonAxes);
            mainState = save_plot2_signal_profile_state( ...
                signalFigure, false, mainAxes);
            testCase.verifyEqual(comparisonState.name, 'Comparison');
            testCase.verifyEqual(comparisonState.signalIds, {'MSG.A'});
            testCase.verifyEqual(mainState.name, 'Main');
            testCase.verifyEqual(mainState.signalIds, {'MSG.B'});

            xlim(mainAxes, [2 6]);
            testCase.verifyEqual(xlim(comparisonAxes), [2 6]);

            mainToggle.Value = true;
            toggle_cursor_tool(mainToggle, [], signalFigure);
            update_cursor_tool(signalFigure, 3.5);
            testCase.verifyTrue(signalFigure.UserData.cursorTool.enabled);
            testCase.verifyEqual( ...
                signalFigure.UserData.cursorTool.currentTime, 3.5);
            testCase.verifyEqual( ...
                signalFigure.UserData.cursorTool.cursorLine.Value, 3.5);
            testCase.verifyEqual( ...
                signalFigure.UserData.cursorTool.comparisonCursorLine.Value, 3.5);

            update_cursor_tool(signalFigure, 4.5);
            testCase.verifyEqual( ...
                signalFigure.UserData.cursorTool.comparisonCursorLine.Value, 4.5);

            start_plot2_cursor_drag( ...
                signalFigure.UserData.cursorTool.comparisonCursorLine, signalFigure);
            testCase.verifyEqual( ...
                signalFigure.UserData.cursorTool.activeAxes, comparisonAxes);
            signalFigure.UserData.cursorTool.dragging = false;

            mainToggle.Value = false;
            toggle_cursor_tool(mainToggle, [], signalFigure);
            testCase.verifyFalse(signalFigure.UserData.cursorTool.enabled);
            testCase.verifyEqual(string( ...
                signalFigure.UserData.cursorTool.comparisonCursorLine.Visible), "off");
        end
    end
end

function delete_figure_if_valid(figureHandle)
if isgraphics(figureHandle)
    delete(figureHandle);
end
end
